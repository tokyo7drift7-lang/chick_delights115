      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Keulen parieren</h3><p>Jede Keule am Knochen halten und das Fleisch zum dicken Ende schieben, dabei nach außen stülpen. Lose Sehnen abziehen. Ziel ist eine saubere Kugel Fleisch an einem blanken Knochen.</p></div></li>
        <li><div><h3>Würzen und bestäuben</h3><p>Die Lollis mit Speisestärke, Paprika, Knoblauchpulver, Salz und Öl vermengen, bis alles gleichmäßig überzogen ist.</p></div></li>
        <li><div><h3>Garen</h3><p>Den Ofen auf 200 °C vorheizen. Die Lollis mit der Knochenseite nach oben auf ein belegtes Blech legen und 18 Minuten backen.</p></div></li>
        <li><div><h3>Glasur anrühren</h3><p>Sojasauce, Honig, Sriracha und Reisessig in einer kleinen Schüssel verrühren.</p></div></li>
        <li><div><h3>Glasieren und fertig garen</h3><p>Die Lollis großzügig mit der Glasur bestreichen und weitere 7 bis 8 Minuten backen, einmal wenden, bis sie klebrig sind und die dickste Stelle 75 °C erreicht.</p></div></li>
        <li><div><h3>Servieren</h3><p>Mit Sesamsamen und Frühlingszwiebel bestreuen und heiß servieren. Servietten bereitstellen und akzeptieren, dass sie niemand benutzt.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Wenn die Zeit knapp ist, den Metzger bitten, die Keulen zu parieren. Viele machen das kostenlos.</li>
          <li>Das Blech auslegen. Die Glasur wird zu Karamell und verschmilzt mit blankem Metall.</li>
          <li>Die Glasur funktioniert auch für Flügel: 30 Minuten bei 200 °C garen, dann glasieren und 8 Minuten fertig backen.</li>
        </ul>
      </section>

