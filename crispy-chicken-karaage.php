      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Hähnchen marinieren</h3><p>Sojasauce, Sake, Ingwer, Knoblauch, Zucker und Salz in einer Schüssel verrühren. Die Hähnchenstücke dazugeben, alles gut vermengen und 15 Minuten bei Raumtemperatur stehen lassen. Für mehr Geschmack abgedeckt bis zu 1 Stunde kalt stellen.</p></div></li>
        <li><div><h3>Öl erhitzen</h3><p>Das Öl in einen tiefen Topf geben, höchstens bis zu einem Drittel der Höhe, und auf 170 °C erhitzen. Ein Thermometer im Topf lassen; Karaage braucht vor allem eine gleichmäßige Temperatur, nicht die heißeste.</p></div></li>
        <li><div><h3>In Stärke wenden</h3><p>Das Hähnchen aus der Marinade heben und abtropfen lassen. Portionsweise in der Kartoffelstärke wenden und leicht andrücken, damit sie haftet, dann überschüssiges Pulver abschütteln.</p></div></li>
        <li><div><h3>Erster Durchgang</h3><p>In Portionen von sechs bis acht Stücken 3 bis 4 Minuten frittieren, bis sie blassgolden sind. In den ersten 30 Sekunden nicht rühren, sonst löst sich die Panade. Auf ein Gitter heben und 4 Minuten ruhen lassen.</p></div></li>
        <li><div><h3>Zweiter Durchgang</h3><p>Das Öl auf 190 °C erhitzen und jede Portion nochmals 60 bis 90 Sekunden frittieren, bis sie tiefgolden und hörbar knusprig ist. Das doppelte Frittieren hält die Panade leicht statt fettig.</p></div></li>
        <li><div><h3>Sofort servieren</h3><p>Auf einem Gitter abtropfen lassen, nie auf Küchenpapier, und heiß mit etwas zusätzlichem Salz würzen. Mit Zitronenspalten und japanischer Mayonnaise servieren.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Kartoffelstärke ergibt die herrlich leichte Kruste. Speisestärke funktioniert, normales Mehl nicht.</li>
          <li>Das Hähnchen zwischen den Durchgängen ruhen lassen. So gart es innen durch und die Panade setzt sich, damit sie beim zweiten Frittieren knusprig bleibt.</li>
          <li>Erst bei 170 °C, dann bei 190 °C frittieren. Wenn das Öl raucht, den Topf eine Minute vom Herd nehmen.</li>
        </ul>
      </section>

