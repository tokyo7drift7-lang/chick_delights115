      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Hähnchen beizen</h3><p>Buttermilch, scharfe Sauce, die Hälfte des Paprikas, die Hälfte des Knoblauch- und Zwiebelpulvers sowie das Salz verrühren. Die Keulen dazugeben, abdecken und mindestens 4 Stunden, idealerweise über Nacht, kalt stellen.</p></div></li>
        <li><div><h3>Panade mischen</h3><p>Weizenmehl, Speisestärke, Backpulver, schwarzen Pfeffer und die restlichen Gewürze in einer breiten Schüssel vermengen. Gut durchrühren, damit sich alles gleichmäßig verteilt.</p></div></li>
        <li><div><h3>Wenden und ruhen lassen</h3><p>Jede Keule aus der Buttermilch heben und abtropfen lassen. Kräftig ins Mehl drücken, wenden und erneut drücken. Die panierten Stücke 10 Minuten auf einem Gitter ruhen lassen, damit die Kruste Feuchtigkeit aufnimmt.</p></div></li>
        <li><div><h3>Öl erhitzen</h3><p>Das Öl in einem schweren Topf auf 165 °C erhitzen. Es sollte höchstens bis zur Hälfte der Topfwand reichen.</p></div></li>
        <li><div><h3>Portionsweise frittieren</h3><p>Drei bis vier Stücke gleichzeitig 8 bis 10 Minuten frittieren und alle zwei Minuten wenden, bis die Kruste tiefgolden ist und die dickste Stelle 75 °C erreicht.</p></div></li>
        <li><div><h3>Abtropfen und ruhen</h3><p>Auf ein Gitter über einem Blech heben und 5 Minuten ruhen lassen. Das ist nicht optional: Die Säfte müssen sich setzen, sonst laufen sie beim ersten Bissen heraus.</p></div></li>
        <li><div><h3>Honig-Chili</h3><p>Den Honig mit den Chiliflocken 30 Sekunden erwärmen und kurz vor dem Servieren über das Hähnchen träufeln.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Ein Thermometer entscheidet zwischen saftig und roh. 75 °C am Knochen, jedes Mal.</li>
          <li>Das panierte Hähnchen vor dem Frittieren 10 Minuten ruhen lassen. Trockenes Mehl fällt ab, feuchtes bleibt haften.</li>
          <li>Bei 165 °C frittieren. Heißeres Öl bräunt die Kruste, bevor die Mitte gar ist.</li>
        </ul>
      </section>

