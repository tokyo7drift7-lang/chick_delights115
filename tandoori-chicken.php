      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Marinieren</h3><p>Joghurt, Tandoori Masala, Chilipulver, Ingwer-Knoblauch-Paste, Zitronensaft und Salz verrühren. Die Schenkel zweimal mit dem Messer einschneiden, gut einreiben und 30 Minuten stehen lassen. Über Nacht ist besser.</p></div></li>
        <li><div><h3>Ofen vorheizen</h3><p>Den Ofen auf 220 °C vorheizen, mit einem großen Blech darin. Ein vorgeheiztes Blech beginnt sofort mit dem Garen, wenn das Hähnchen darauf liegt.</p></div></li>
        <li><div><h3>Blech belegen</h3><p>Die Zwiebelspalten mit dem Öl vermengen und auf dem heißen Blech verteilen. Das Hähnchen daraufsetzen, mit Abstand zueinander, damit es röstet statt dämpft.</p></div></li>
        <li><div><h3>Garen</h3><p>22 bis 25 Minuten backen, bis die dickste Stelle 75 °C erreicht. Nach der Hälfte die Marinade aus dem Blech darüberlöffeln.</p></div></li>
        <li><div><h3>Unter dem Grill rösten</h3><p>Den Ofen auf die höchste Grillstufe stellen und 4 bis 5 Minuten garen, bis die Ränder stellenweise schwarz werden. Gut aufpassen: Zwischen geröstet und verbrannt liegen etwa 30 Sekunden.</p></div></li>
        <li><div><h3>Ruhen und servieren</h3><p>5 Minuten ruhen lassen, dann mit Zitrone beträufeln und mit Koriander bestreuen. Mit den gerösteten Zwiebeln und einem Löffel Joghurt servieren.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Schenkel mit Knochen bleiben bei dieser Hitze saftiger als Brust. Mit Brust die Garzeit auf 18 Minuten verkürzen.</li>
          <li>Kashmiri-Chili färbt, ohne zu brennen. Normales Chilipulver macht das Gericht deutlich schärfer.</li>
          <li>Kein Grill? Die letzten 6 Minuten bei 240 °C fertig garen.</li>
        </ul>
      </section>

