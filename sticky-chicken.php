      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Hähnchen bestäuben</h3><p>Das Hähnchen mit der Speisestärke vermengen, bis jedes Stück dünn und gleichmäßig bestäubt ist. Das bindet später die Glasur.</p></div></li>
        <li><div><h3>Scharf anbraten</h3><p>Das neutrale Öl in einer breiten Pfanne bei hoher Hitze erhitzen. Das Hähnchen in einer Lage hineingeben und 3 Minuten nicht anfassen, dann wenden und weitere 3 bis 4 Minuten braten, bis es gebräunt, aber nicht durchgegart ist.</p></div></li>
        <li><div><h3>Glasur aufbauen</h3><p>Das Hähnchen an den Pfannenrand schieben. Ingwer und Knoblauch in die Mitte geben und 30 Sekunden garen, bis sie duften.</p></div></li>
        <li><div><h3>Reduzieren</h3><p>Sojasauce, Honig, Reisessig und Sesamöl angießen. Alles verrühren und 2 Minuten sprudeln lassen, bis die Sauce zu binden beginnt.</p></div></li>
        <li><div><h3>Schwenken bis klebrig</h3><p>Die Hitze auf mittel stellen und das Hähnchen 2 bis 3 Minuten in der Glasur schwenken, bis jedes Stück überzogen ist und die Sauce haftet statt zu pftützen.</p></div></li>
        <li><div><h3>Fertigstellen</h3><p>Die Pfanne vom Herd nehmen, Sesamsamen und Frühlingszwiebeln darüberstreuen und sofort mit Reis und etwas Grünem servieren.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Das Hähnchen in gleichmäßige 3-cm-Stücke schneiden, damit alles gleichzeitig gart.</li>
          <li>Wird die Glasur zu fest, mit 1 EL Wasser vom Herd lösen. Beim Abkühlen bindet sie wieder.</li>
          <li>Die Glasur doppelt ansetzen und die Hälfte für ein Stir-fry später in der Woche aufheben.</li>
        </ul>
      </section>

