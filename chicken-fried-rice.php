      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Alles vorbereiten</h3><p>Gebratener Reis geht schnell. Reis, Hähnchen, Gemüse und Saucen in Reichweite haben, bevor die Pfanne auf den Herd kommt.</p></div></li>
        <li><div><h3>Eier verrühren</h3><p>1 EL Öl im Wok bei höchster Hitze erhitzen. Die Eier hineingeben und 30 Sekunden verrühren, dann auf einen Teller geben.</p></div></li>
        <li><div><h3>Gemüse anbraten</h3><p>Das restliche Öl, dann Karotte und die weißen Teile der Frühlingszwiebeln zugeben. 2 Minuten pfannenrühren.</p></div></li>
        <li><div><h3>Reis zugeben</h3><p>Den kalten Reis hineingeben und in die Pfanne drücken. 30 Sekunden stehen lassen, dann die Klumpen mit dem Löffelrücken zerdrücken. 3 Minuten wiederholen, bis der Reis heiß ist und zu knistern beginnt.</p></div></li>
        <li><div><h3>Hähnchen und Erbsen</h3><p>Hähnchen, Erbsen und Sojasauce einrühren und 2 Minuten garen, bis die Erbsen heiß und das Hähnchen durchgewärmt ist.</p></div></li>
        <li><div><h3>Fertigstellen</h3><p>Die Eier mit Sesamöl, weißem Pfeffer und den grünen Frühlingszwiebelringen zurück in die Pfanne geben. 30 Sekunden schwenken und sofort servieren.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Reis von gestern ist trockener und brät, statt zu dämpfen. Frischer Reis muss erst eine Stunde offen abkühlen.</li>
          <li>Erst am Tisch nachsalzen, nachdem du probiert hast. Sojasauce ist viel salziger, als sie aussieht.</li>
          <li>Kein Wok? Die breiteste Pfanne nehmen, die du hast, und in zwei Portionen braten. Zu viel auf einmal macht den Reis matschig.</li>
        </ul>
      </section>

