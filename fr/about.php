  <section class="section section-white page-body">
    <div class="container prose">
      <h2>Pourquoi ce site existe</h2>
      <p>La plupart des recettes de poulet en ligne sont &eacute;crites pour le r&eacute;f&eacute;rencement, pas pour cuisiner. Vous faites d&eacute;filer un souvenir d'enfance, trois blocs publicitaires et une galerie photo avant de d&eacute;couvrir &agrave; quelle temp&eacute;rature chauffer le four. Chick Delights fait l'inverse&nbsp;: la m&eacute;thode commence &agrave; l'&eacute;tape un, les quantit&eacute;s sont en grammes et les astuces sont en bas, l&agrave; o&ugrave; elles ont leur place.</p>
      <p>Chaque recette a &eacute;t&eacute; cuisin&eacute;e dans une cuisine domestique normale, sur un feu normal, avec du mat&eacute;riel que vous poss&eacute;dez probablement d&eacute;j&agrave;. Pas de sous-vide, pas de chalumeau, pas d'ingr&eacute;dients &agrave; importer.</p>

      <h2>Notre m&eacute;thode de test</h2>
      <p><strong>Premi&egrave;re cuisson.</strong> Nous &eacute;crivons une id&eacute;e, la cuisinons une fois et corrigeons les probl&egrave;mes &eacute;vidents&nbsp;: poulet sec, sauce qui tranche, laquage trop liquide.</p>
      <p><strong>Deuxi&egrave;me cuisson.</strong> Nous recommen&ccedil;ons en suivant uniquement la m&eacute;thode &eacute;crite, sans notes de la premi&egrave;re fois. Si nous devons deviner, la m&eacute;thode est fausse.</p>
      <p><strong>Troisi&egrave;me cuisson.</strong> Une autre personne suit la page de z&eacute;ro et signale tout ce qui n'est pas clair. C'est seulement ensuite que la recette est publi&eacute;e.</p>
      <p>Nous gardons aussi un thermom&egrave;tre dans la partie la plus &eacute;paisse de chaque morceau. Le poulet est cuit &agrave; 75&nbsp;&deg;C, et ce chiffre appara&icirc;t dans la m&eacute;thode de chaque recette du site.</p>

      <h2>Ce que nous ne faisons pas</h2>
      <ul>
        <li><strong>Aucune quantit&eacute; invent&eacute;e.</strong> Si un chiffre figure sur la page, il a &eacute;t&eacute; pes&eacute;.</li>
        <li><strong>Aucun placement payant.</strong> Aucune marque ne paie pour appara&icirc;tre dans une recette.</li>
        <li><strong>Aucune promesse nutritionnelle.</strong> Les tableaux nutritionnels sont des estimations, pas un avis m&eacute;dical.</li>
        <li><strong>Pas d'histoire d'origine de 2&nbsp;000 mots.</strong> La recette passe d'abord.</li>
      </ul>

      <h2>La cuisine</h2>
      <p>Chick Delights est anim&eacute; par Emma Johnson depuis une cuisine domestique &agrave; Gaston, en Caroline du Sud, avec un four qui chauffe environ 5&nbsp;&deg;C de trop. C'est pr&eacute;cis&eacute; ici parce que cela compte&nbsp;: si votre four chauffe trop peu, ajoutez cinq minutes et v&eacute;rifiez au thermom&egrave;tre plut&ocirc;t qu'&agrave; l'horloge.</p>

      <h2>Corrections</h2>
      <p>Si une recette ne fonctionne pas, nous voulons le savoir. &Eacute;crivez &agrave; <a href="mailto:info@chickdelights.site">info@chickdelights.site</a> avec le nom de la recette, ce qui s'est pass&eacute; et une photo si vous en avez une. Les corrections sont not&eacute;es sur la page avec leur date.</p>
