      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Parer les pilons</h3><p>Tenez chaque pilon par l'os et repoussez la viande vers le bout épais en la retournant comme un gant. Retirez les tendons qui pendent. Visez une boule de viande nette sur un os propre.</p></div></li>
        <li><div><h3>Assaisonner et enrober</h3><p>Mélangez les sucettes avec la fécule, le paprika, l'ail en poudre, le sel et l'huile jusqu'à un enrobage régulier.</p></div></li>
        <li><div><h3>Rôtir</h3><p>Préchauffez le four à 200 °C. Étalez les sucettes sur une plaque chemisée, os vers le haut, et enfournez 18 minutes.</p></div></li>
        <li><div><h3>Préparer le laquage</h3><p>Mélangez la sauce soja, le miel, la Sriracha et le vinaigre de riz dans un petit bol.</p></div></li>
        <li><div><h3>Laquer et finir</h3><p>Badigeonnez généreusement les sucettes de laquage et enfournez 7 à 8 minutes de plus, en retournant une fois, jusqu'à ce qu'elles soient collantes et à 75 °C à cœur.</p></div></li>
        <li><div><h3>Servir</h3><p>Parsemez de graines de sésame et d'oignon nouveau et servez chaud. Prévoyez des serviettes et acceptez que personne ne les utilise.</p></div></li>
      </ol>

