      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Colorer le poulet</h3><p>Chauffez 1 c. à s. de ghee dans une cocotte à feu vif. Colorez le poulet en deux fournées, environ 3 minutes chacune, puis réservez. Ne le cuisez pas à cœur.</p></div></li>
        <li><div><h3>Construire la base</h3><p>Baissez le feu, ajoutez le reste de ghee et les graines de cumin. Quand elles grésillent, ajoutez l'oignon et cuisez 8 minutes, jusqu'à ce qu'il soit tendre et doré sur les bords.</p></div></li>
        <li><div><h3>Ajouter les aromates</h3><p>Incorporez la pâte gingembre-ail et cuisez 1 minute, jusqu'à ce que l'odeur crue disparaisse. Ne la laissez pas brunir.</p></div></li>
        <li><div><h3>Cuire la tomate</h3><p>Ajoutez le coulis, le curcuma, le garam masala, le piment et le sel. Cuisez 10 minutes à feu moyen, jusqu'à ce que la sauce fonce et que l'huile commence à se séparer sur les bords.</p></div></li>
        <li><div><h3>Mijoter le poulet</h3><p>Remettez le poulet et ses jus dans la cocotte avec 100 ml d'eau. Couvrez et laissez mijoter doucement 15 minutes, jusqu'à ce que le poulet soit cuit à cœur.</p></div></li>
        <li><div><h3>Finir à la crème</h3><p>Baissez le feu, incorporez la crème et le piment vert fendu, et laissez mijoter à découvert 3 minutes. Goûtez et ajustez le sel.</p></div></li>
        <li><div><h3>Reposer</h3><p>Retirez la cocotte du feu et laissez reposer 5 minutes avant de parsemer de coriandre. Servez avec du riz ou du roti.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>Colorer le poulet d'abord donne sa profondeur à la sauce. Ne sautez pas cette étape.</li>
          <li>Laissez la tomate cuire jusqu'à ce que l'huile se sépare. Aller trop vite donne un curry plat.</li>
          <li>Le curry est meilleur le lendemain. Refroidissez vite, placez au frais et réchauffez doucement avec un peu d'eau.</li>
        </ul>
      </section>

