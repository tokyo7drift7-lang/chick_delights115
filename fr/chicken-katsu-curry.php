      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Lancer la sauce</h3><p>Chauffez 1 c. à s. d'huile dans une poêle et faites cuire l'oignon et les carottes 8 minutes, jusqu'à ce qu'ils soient tendres et à peine colorés.</p></div></li>
        <li><div><h3>Construire le curry</h3><p>Incorporez le curry et la farine supplémentaire et cuisez 1 minute. Versez le bouillon petit à petit en fouettant pour éviter les grumeaux. Ajoutez la sauce soja et le miel et laissez mijoter 12 minutes.</p></div></li>
        <li><div><h3>Mixer</h3><p>Mixez la sauce jusqu'à ce qu'elle soit lisse, remettez-la dans la poêle et gardez au chaud. Si elle est trop épaisse, détendez-la avec un peu de bouillon.</p></div></li>
        <li><div><h3>Paner le poulet</h3><p>Ouvrez chaque blanc en portefeuille pour une épaisseur régulière de 1,5 cm et salez. Passez dans la farine, puis l'œuf, puis le panko en pressant fermement.</p></div></li>
        <li><div><h3>Frire les escalopes</h3><p>Chauffez le reste de l'huile dans une poêle large à feu moyen. Faites frire les escalopes 3 à 4 minutes par face, jusqu'à une couleur dorée profonde et 75 °C à cœur. Cuisez en deux fournées pour que la poêle reste chaude.</p></div></li>
        <li><div><h3>Reposer et trancher</h3><p>Laissez reposer les escalopes 3 minutes sur une grille, puis détaillez-les en lanières. Le repos garde la panure attachée à la découpe.</p></div></li>
        <li><div><h3>Servir</h3><p>Nappez le riz de curry et posez les lanières de katsu dessus. Servez immédiatement, avec du gingembre mariné si vous en avez.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>Ouvrir le blanc en portefeuille, c'est la différence entre un katsu sec et un katsu juteux. Visez une épaisseur régulière.</li>
          <li>Du panko, pas de la chapelure ordinaire. C'est son floconneux qui rend la croûte croustillante.</li>
          <li>La sauce se congèle jusqu'à 2 mois. Faites-en le double et remerciez-vous plus tard.</li>
        </ul>
      </section>

