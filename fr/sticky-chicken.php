      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Enrober le poulet</h3><p>Mélangez le poulet avec la fécule jusqu'à ce que chaque morceau soit finement et régulièrement enrobé. C'est ce qui épaissira le laquage ensuite.</p></div></li>
        <li><div><h3>Saisir vivement</h3><p>Chauffez l'huile neutre dans une poêle large à feu vif. Ajoutez le poulet en une seule couche et ne touchez à rien pendant 3 minutes, puis retournez et cuisez encore 3 à 4 minutes, jusqu'à ce qu'il soit doré mais pas cuit à cœur.</p></div></li>
        <li><div><h3>Monter le laquage</h3><p>Poussez le poulet sur le bord de la poêle. Mettez le gingembre et l'ail au centre et cuisez 30 secondes, jusqu'à ce qu'ils embaument.</p></div></li>
        <li><div><h3>Réduire</h3><p>Versez la sauce soja, le miel, le vinaigre de riz et l'huile de sésame. Mélangez et laissez bouillonner 2 minutes, jusqu'à ce que la sauce commence à épaissir.</p></div></li>
        <li><div><h3>Enrober jusqu'à ce que ça colle</h3><p>Passez à feu moyen et enrobez le poulet du laquage 2 à 3 minutes, jusqu'à ce que chaque morceau soit nappé et que la sauce adhère au lieu de stagner.</p></div></li>
        <li><div><h3>Finir</h3><p>Retirez la poêle du feu, parsemez de graines de sésame et d'oignons nouveaux, et servez aussitôt avec du riz et quelque chose de vert.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>Coupez le poulet en morceaux réguliers de 3 cm pour une cuisson uniforme.</li>
          <li>Si le laquage se resserre trop, détendez-le avec 1 c. à s. d'eau hors du feu. Il épaissit de nouveau en refroidissant.</li>
          <li>Doublez le laquage et gardez la moitié pour un sauté plus tard dans la semaine.</li>
        </ul>
      </section>

