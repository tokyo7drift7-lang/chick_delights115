      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Mariner</h3><p>Fouettez le yaourt, le tandoori masala, le piment en poudre, la pâte gingembre-ail, le jus de citron et le sel. Entaillez deux fois chaque cuisse au couteau, enrobez-la bien et laissez 30 minutes. Toute une nuit, c'est mieux.</p></div></li>
        <li><div><h3>Chauffer le four</h3><p>Préchauffez le four à 220 °C avec une grande plaque à l'intérieur. Une plaque brûlante lance la cuisson dès que le poulet se pose dessus.</p></div></li>
        <li><div><h3>Monter la plaque</h3><p>Mélangez les quartiers d'oignon avec l'huile et étalez-les sur la plaque chaude. Posez le poulet dessus en espaçant les morceaux pour qu'il rôtisse au lieu de cuire à la vapeur.</p></div></li>
        <li><div><h3>Rôtir</h3><p>Enfournez 22 à 25 minutes, jusqu'à 75 °C à cœur. À mi-cuisson, arrosez avec la marinade accumulée sur la plaque.</p></div></li>
        <li><div><h3>Dorer sous le gril</h3><p>Passez le four en position gril maximale et cuisez 4 à 5 minutes, jusqu'à ce que les bords noircissent par endroits. Surveillez : il y a environ 30 secondes entre doré et brûlé.</p></div></li>
        <li><div><h3>Reposer et servir</h3><p>Laissez reposer 5 minutes, puis pressez le citron et parsemez de coriandre. Servez avec les oignons rôtis et une cuillère de yaourt.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>Les cuisses avec os restent plus juteuses que le blanc à cette température. Avec du blanc, réduisez la cuisson à 18 minutes.</li>
          <li>Le piment du Cachemire colore sans brûler. Un piment ordinaire rendra le plat nettement plus fort.</li>
          <li>Pas de gril ? Terminez 6 minutes à 240 °C.</li>
        </ul>
      </section>

