      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Mariner</h3><p>Mélangez le yaourt, le paprika, le cumin, la coriandre, le Cayenne, l'ail, l'huile, le sel et la moitié du jus de citron. Incorporez le poulet, couvrez et laissez 15 minutes pendant que le gril chauffe.</p></div></li>
        <li><div><h3>Tremper les brochettes</h3><p>Si vous utilisez des brochettes en bois, faites-les tremper 10 minutes dans l'eau pour qu'elles ne brûlent pas. Les brochettes métalliques n'ont besoin de rien.</p></div></li>
        <li><div><h3>Monter les brochettes</h3><p>Enfilez le poulet en alternant avec l'oignon et le poivron. Laissez un petit espace entre les morceaux pour que la chaleur atteigne chaque face.</p></div></li>
        <li><div><h3>Griller</h3><p>Grillez à feu moyen-vif 12 à 15 minutes, en retournant toutes les 3 minutes, jusqu'à ce que les bords soient marqués et le cœur à 75 °C.</p></div></li>
        <li><div><h3>Reposer</h3><p>Laissez reposer les brochettes 3 minutes, puis arrosez du reste de jus de citron et salez légèrement.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>La cuisse est bien plus indulgente que le blanc sur le gril. Avec du blanc, réduisez le temps d'un tiers.</li>
          <li>Ne serrez pas les brochettes. C'est l'air qui donne des marques plutôt que de la vapeur.</li>
          <li>Pas de gril ? Une poêle striée à feu vif fait l'affaire ; cuisez en deux fournées pour qu'elle reste chaude.</li>
        </ul>
