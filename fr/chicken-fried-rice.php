      <h2>Méthode</h2>
      <ol class="steps">
        <li><div><h3>Tout préparer</h3><p>Le riz sauté va vite. Ayez riz, poulet, légumes et sauces à portée de main avant de poser la poêle sur le feu.</p></div></li>
        <li><div><h3>Brouiller les œufs</h3><p>Chauffez 1 c. à s. d'huile dans un wok à feu maximal. Versez les œufs et brouillez 30 secondes, puis réservez sur une assiette.</p></div></li>
        <li><div><h3>Démarrer les légumes</h3><p>Ajoutez le reste de l'huile, puis la carotte et les blancs d'oignons nouveaux. Faites sauter 2 minutes.</p></div></li>
        <li><div><h3>Ajouter le riz</h3><p>Versez le riz froid et pressez-le dans la poêle. Laissez 30 secondes, puis défaites les grumeaux avec le dos d'une cuillère. Répétez 3 minutes, jusqu'à ce que le riz soit chaud et commence à crépiter.</p></div></li>
        <li><div><h3>Poulet et petits pois</h3><p>Incorporez le poulet, les petits pois et la sauce soja et cuisez 2 minutes, jusqu'à ce que les pois soient chauds et le poulet réchauffé à cœur.</p></div></li>
        <li><div><h3>Finir</h3><p>Remettez les œufs dans la poêle avec l'huile de sésame, le poivre blanc et les verts d'oignons nouveaux. Faites sauter 30 secondes et servez aussitôt.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Notes de cuisine</h2>
        <ul>
          <li>Le riz de la veille est plus sec et saute au lieu de cuire à la vapeur. Le riz frais doit refroidir à découvert une heure.</li>
          <li>N'ajoutez pas de sauce soja à table avant d'avoir goûté. Elle est bien plus salée qu'elle n'en a l'air.</li>
          <li>Pas de wok ? Utilisez la poêle la plus large et cuisez en deux fournées. Trop charger rend le riz spongieux.</li>
        </ul>
      </section>

