  <section class="section section-white page-body">
    <div class="container prose">
      <h2>Warum es diese Seite gibt</h2>
      <p>Die meisten H&auml;hnchenrezepte im Netz sind f&uuml;r Suchmaschinen geschrieben, nicht zum Kochen. Du scrollst an einer Kindheitserinnerung, drei Werbebl&ouml;cken und einer Fotogalerie vorbei, bevor du erf&auml;hrst, wie hei&szlig; der Ofen sein soll. Chick Delights macht es anders: Die Methode beginnt bei Schritt eins, die Mengen stehen in Gramm, und die Tipps stehen unten, wo sie hingeh&ouml;ren.</p>
      <p>Jedes Rezept hier wurde in einer normalen Haushaltsk&uuml;che gekocht, auf einem normalen Herd, mit Ger&auml;ten, die du wahrscheinlich schon besitzt. Kein Sous-vide, kein Bunsenbrenner, keine Zutaten, die extra importiert werden m&uuml;ssen.</p>

      <h2>So testen wir</h2>
      <p><strong>Erster Durchgang.</strong> Wir schreiben eine Idee auf, kochen sie einmal und beheben die offensichtlichen Probleme: trockenes H&auml;hnchen, eine Sauce, die sich trennt, eine Glasur, die zu d&uuml;nn bleibt.</p>
      <p><strong>Zweiter Durchgang.</strong> Wir kochen erneut, nur mit der aufgeschriebenen Methode und ohne Notizen vom ersten Versuch. Wenn wir raten m&uuml;ssen, ist die Methode falsch.</p>
      <p><strong>Dritter Durchgang.</strong> Eine andere Person folgt der Seite von Anfang an und meldet alles Unklare. Erst dann wird ver&ouml;ffentlicht.</p>
      <p>Au&szlig;erdem stecken wir bei jedem St&uuml;ck ein Thermometer in die dickste Stelle. H&auml;hnchen ist bei 75&nbsp;&deg;C gar, und diese Zahl steht in der Methode jedes Rezepts auf dieser Seite.</p>

      <h2>Was wir nicht machen</h2>
      <ul>
        <li><strong>Keine erfundenen Mengen.</strong> Wenn eine Zahl auf der Seite steht, wurde sie abgewogen.</li>
        <li><strong>Keine bezahlten Platzierungen.</strong> Keine Marke zahlt daf&uuml;r, in einem Rezept zu erscheinen.</li>
        <li><strong>Keine N&auml;hrwertversprechen.</strong> Die N&auml;hrwerttabellen sind Sch&auml;tzungen, keine medizinische Beratung.</li>
        <li><strong>Keine 2.000-W&ouml;rter-Vorgeschichte.</strong> Das Rezept kommt zuerst.</li>
      </ul>

      <h2>Die K&uuml;che</h2>
      <p>Chick Delights wird von Emma Johnson aus einer Privatk&uuml;che in Gaston, South Carolina, betrieben, mit einem Ofen, der etwa 5&nbsp;&deg;C zu hei&szlig; l&auml;uft. Das steht hier, weil es wichtig ist: Wenn dein Ofen zu kalt l&auml;uft, gib f&uuml;nf Minuten dazu und pr&uuml;fe mit dem Thermometer statt mit der Uhr.</p>

      <h2>Korrekturen</h2>
      <p>Wenn ein Rezept nicht funktioniert, wollen wir es wissen. Schreib an <a href="mailto:info@chickdelights.site">info@chickdelights.site</a> mit dem Rezeptnamen, was passiert ist, und einem Foto, falls du eines hast. Korrekturen werden mit Datum auf der jeweiligen Seite vermerkt.</p>
