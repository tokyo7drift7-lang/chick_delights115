      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Prep everything first</h3><p>Fried rice moves fast. Have the rice, chicken, vegetables and sauces within reach before the pan goes on the heat.</p></div></li>
        <li><div><h3>Scramble the eggs</h3><p>Heat 1 tbsp of the oil in a wok over the highest heat you have. Pour in the eggs and scramble for 30 seconds, then tip them out onto a plate.</p></div></li>
        <li><div><h3>Start the vegetables</h3><p>Add the remaining oil, then the carrot and the white parts of the spring onions. Stir-fry for 2 minutes.</p></div></li>
        <li><div><h3>Add the rice</h3><p>Tip in the cold rice and press it into the pan. Leave it for 30 seconds, then break up the clumps with the back of a spoon. Repeat for 3 minutes, until the rice is hot and starting to crackle.</p></div></li>
        <li><div><h3>Add chicken and peas</h3><p>Stir in the chicken, peas and soy sauce and cook for 2 minutes, until the peas are hot and the chicken is warmed through.</p></div></li>
        <li><div><h3>Finish</h3><p>Return the eggs to the pan with the sesame oil, white pepper and green spring onion tops. Toss for 30 seconds and serve straight away.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Day-old rice is drier and fries instead of steaming. Fresh rice needs to cool uncovered for an hour first.</li>
          <li>Do not add extra soy sauce at the table until you have tasted it. Takeaway soy is much saltier than it looks.</li>
          <li>No wok? Use the widest frying pan you own and cook in two batches. Crowding is what makes fried rice soggy.</li>
        </ul>
      </section>

