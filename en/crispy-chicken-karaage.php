      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Marinate the chicken</h3><p>Mix the soy sauce, sake, ginger, garlic, sugar and salt in a bowl. Add the chicken pieces, toss to coat, and leave for 15 minutes at room temperature. For a deeper flavour, cover and refrigerate for up to 1 hour.</p></div></li>
        <li><div><h3>Heat the oil</h3><p>Pour the oil into a deep pan to no more than one third of its depth and heat to 170Â° C. Keep a thermometer in the pan; karaage needs a steady temperature more than a hot one.</p></div></li>
        <li><div><h3>Coat in starch</h3><p>Lift the chicken from the marinade and let the excess drip off. Toss in the potato starch a few pieces at a time, pressing so the starch sticks, then shake off the loose powder.</p></div></li>
        <li><div><h3>First fry</h3><p>Fry in batches of six to eight pieces for 3 to 4 minutes, until pale gold. Do not stir for the first 30 seconds or the crust will fall off. Lift onto a rack and rest for 4 minutes.</p></div></li>
        <li><div><h3>Second fry</h3><p>Raise the oil to 190Â° C and fry each batch again for 60 to 90 seconds, until deep gold and audibly crisp. The double fry is what keeps the crust light instead of greasy.</p></div></li>
        <li><div><h3>Serve immediately</h3><p>Drain on a rack, never on kitchen paper, and season with a little extra salt while hot. Serve with lemon wedges and Japanese mayonnaise.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Potato starch gives the shatteringly light crust. Cornflour works, plain flour does not.</li>
          <li>Rest the chicken between fries. This steams the inside and sets the crust so the second fry stays crisp.</li>
          <li>Fry at 170Â° C first, 190Â° C second. If the oil smokes, take the pan off the heat for a minute.</li>
        </ul>
