      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Marinate</h3><p>Whisk the yoghurt, tandoori masala, chilli powder, ginger and garlic paste, lemon juice and salt. Slash the chicken thighs twice with a knife, coat well and leave for 30 minutes. Overnight is better.</p></div></li>
        <li><div><h3>Heat the oven</h3><p>Heat the oven to 220Â° C with a large tray inside. A preheated tray starts the cooking the second the chicken lands on it.</p></div></li>
        <li><div><h3>Build the tray</h3><p>Toss the onion wedges with the oil and spread them over the hot tray. Sit the chicken on top, spacing the pieces apart so they roast rather than steam.</p></div></li>
        <li><div><h3>Roast</h3><p>Roast for 22 to 25 minutes, until the thickest part reads 75Â° C. Spoon over any marinade that has collected in the tray halfway through.</p></div></li>
        <li><div><h3>Char under the grill</h3><p>Switch the oven to its hottest grill setting and cook for 4 to 5 minutes, until the edges blacken in spots. Watch it: the line between charred and burnt is about 30 seconds.</p></div></li>
        <li><div><h3>Rest and serve</h3><p>Rest for 5 minutes, then squeeze over the lemon and scatter with coriander. Serve with the charred onions and a spoon of yoghurt.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Bone-in thighs stay juicier than breast at this heat. If using breast, cut the roast to 18 minutes.</li>
          <li>Kashmiri chilli gives colour without heat. Ordinary chilli powder will make this noticeably hotter.</li>
          <li>No grill? Finish at 240Â° C for the last 6 minutes.</li>
        </ul>
