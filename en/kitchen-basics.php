      <h2>1. Temperature beats time</h2>
      <p>Every recipe here says &ldquo;until 75&deg;C in the thickest part&rdquo;. That is the number that matters. A thin thigh can be done in 12 minutes; a thick breast can take 22. A cheap instant-read thermometer removes the guesswork for good.</p>

      <h2>2. Salt early, not at the end</h2>
      <p>Salt 30 minutes before cooking, or the night before for larger pieces. Salt pulls moisture to the surface, dissolves, and goes back in as seasoned brine. Salting at the end only seasons the outside.</p>

      <h2>3. Brine with buttermilk or yoghurt</h2>
      <p>Both are mildly acidic and thick enough to cling. Eight hours in buttermilk does more for a chicken thigh than any rub. Yoghurt works the same way for tandoori-style marinades.</p>

      <h2>4. Rest before you cut</h2>
      <p>Five minutes on a board, loosely covered. Juices that would run onto the plate redistribute through the meat instead. Cut immediately and you lose them.</p>

      <h2>5. Thaw safely</h2>
      <p>In the fridge, on the bottom shelf, in a bowl. Never on the counter. A 1.5 kg bird needs about 24 hours. Smaller pieces need 8&ndash;12.</p>

      <h2>6. Freeze with a plan</h2>
      <p>Freeze flat in portions, label with the date, and use within three months. Thaw in the fridge overnight — never in warm water.</p>

