      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>French the drumettes</h3><p>Hold each drumette by the bone and push the meat down towards the thick end, turning it inside out as you go. Pull off any loose sinew. You are aiming for a neat ball of meat on a clean bone.</p></div></li>
        <li><div><h3>Season and coat</h3><p>Toss the lollipops with the cornflour, paprika, garlic powder, salt and oil until evenly coated.</p></div></li>
        <li><div><h3>Roast</h3><p>Heat the oven to 200Â° C. Spread the lollipops on a lined tray, bone side up, and roast for 18 minutes.</p></div></li>
        <li><div><h3>Make the glaze</h3><p>Stir the soy sauce, honey, Sriracha and rice vinegar together in a small bowl.</p></div></li>
        <li><div><h3>Glaze and finish</h3><p>Brush the lollipops generously with the glaze and roast for a further 7 to 8 minutes, turning once, until sticky and 75Â° C at the thickest part.</p></div></li>
        <li><div><h3>Serve</h3><p>Scatter with sesame seeds and spring onion and serve hot. Provide napkins and accept that nobody will use them.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Ask the butcher to french the drumettes if you are short on time. Many will do it free.</li>
          <li>Line the tray. The glaze turns to caramel and will weld itself to bare metal.</li>
          <li>The glaze also works on wings: cook them for 30 minutes at 200Â° C, then glaze and finish for 8.</li>
