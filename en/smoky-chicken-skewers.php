      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Marinate</h3><p>Stir the yoghurt, paprika, cumin, coriander, cayenne, garlic, oil, salt and half the lemon juice together. Fold in the chicken, cover and leave for 15 minutes while the grill heats.</p></div></li>
        <li><div><h3>Soak the skewers</h3><p>If you are using wooden skewers, soak them in water for 10 minutes so they do not burn. Metal skewers need nothing.</p></div></li>
        <li><div><h3>Thread</h3><p>Thread the chicken onto the skewers, alternating with onion and pepper. Leave a small gap between pieces so the heat can reach every side.</p></div></li>
        <li><div><h3>Grill</h3><p>Grill over medium-high heat for 12 to 15 minutes, turning every 3 minutes, until charred at the edges and 75Â° C in the centre.</p></div></li>
        <li><div><h3>Rest</h3><p>Rest the skewers for 3 minutes, then squeeze over the remaining lemon juice and season with a little salt.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Thigh meat is far more forgiving than breast on a grill. If you only have breast, reduce the time by a third.</li>
          <li>Do not pack the skewers tight. Airflow is what gives you char instead of steam.</li>
          <li>No grill? A ridged pan over high heat works; cook in two batches so the pan stays hot.</li>
        </ul>
      </section>

