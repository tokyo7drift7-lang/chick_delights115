      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Coat the chicken</h3><p>Toss the chicken with the cornflour until every piece has a thin, even dusting. This is what thickens the glaze later.</p></div></li>
        <li><div><h3>Sear hard</h3><p>Heat the neutral oil in a wide pan over high heat. Add the chicken in a single layer and leave it alone for 3 minutes, then turn and cook for another 3 to 4 minutes, until browned but not cooked through.</p></div></li>
        <li><div><h3>Build the glaze</h3><p>Push the chicken to the edge of the pan. Add the ginger and garlic to the centre and cook for 30 seconds, until fragrant.</p></div></li>
        <li><div><h3>Reduce</h3><p>Pour in the soy sauce, honey, rice vinegar and sesame oil. Stir everything together and let it bubble for 2 minutes, until the sauce starts to thicken.</p></div></li>
        <li><div><h3>Toss until sticky</h3><p>Return the heat to medium and toss the chicken in the glaze for 2 to 3 minutes, until every piece is coated and the sauce clings rather than pools.</p></div></li>
        <li><div><h3>Finish</h3><p>Take the pan off the heat, scatter over the sesame seeds and spring onions, and serve immediately with rice and something green.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Cut the chicken into even 3 cm pieces so they cook at the same rate.</li>
          <li>If the glaze tightens too much, loosen it with 1 tbsp water off the heat. It thickens again as it cools.</li>
          <li>Double the glaze and keep half back for a stir-fry later in the week.</li>
        </ul>
      </section>

