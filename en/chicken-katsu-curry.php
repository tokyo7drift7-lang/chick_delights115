      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Start the sauce</h3><p>Heat 1 tbsp of the oil in a pan and cook the onion and carrot for 8 minutes, until soft and just catching colour.</p></div></li>
        <li><div><h3>Build the curry</h3><p>Stir in the curry powder and the extra flour and cook for 1 minute. Pour in the stock a little at a time, whisking so no lumps form. Add the soy sauce and honey and simmer for 12 minutes.</p></div></li>
        <li><div><h3>Blend</h3><p>Blend the sauce until smooth, then return it to the pan and keep warm. If it is too thick, loosen with a splash of stock.</p></div></li>
        <li><div><h3>Bread the chicken</h3><p>Butterfly each breast so it is an even 1.5 cm thick and season with the salt. Coat in flour, then egg, then panko, pressing the crumbs on firmly.</p></div></li>
        <li><div><h3>Fry the cutlets</h3><p>Heat the remaining oil in a wide pan over medium heat. Fry the cutlets for 3 to 4 minutes on each side, until deep gold and 75Â° C in the centre. Cook in two batches so the pan stays hot.</p></div></li>
        <li><div><h3>Rest and slice</h3><p>Rest the cutlets on a rack for 3 minutes, then slice into strips. Resting keeps the crust attached when you cut.</p></div></li>
        <li><div><h3>Serve</h3><p>Spoon the curry over the rice and lay the sliced katsu on top. Serve straight away, with pickled ginger if you have it.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Butterflying the breast is the difference between dry katsu and juicy katsu. Aim for an even thickness.</li>
          <li>Panko, not ordinary breadcrumbs. The flaky crumb is what makes the crust shatter.</li>
          <li>The sauce freezes well for up to 2 months. Make double and thank yourself later.</li>
        </ul>
      </section>

