      <h2>Method</h2>
      <ol class="steps">
        <li><div><h3>Brown the chicken</h3><p>Heat 1 tbsp of the ghee in a deep pan over high heat. Brown the chicken in two batches, about 3 minutes each, then set aside. Do not cook it through.</p></div></li>
        <li><div><h3>Build the base</h3><p>Lower the heat, add the remaining ghee and the cumin seeds. When they sizzle, add the onion and cook for 8 minutes, until soft and golden at the edges.</p></div></li>
        <li><div><h3>Add the aromatics</h3><p>Stir in the ginger and garlic paste and cook for 1 minute, until the raw smell disappears. Do not let it brown.</p></div></li>
        <li><div><h3>Cook the tomato</h3><p>Add the passata, turmeric, garam masala, chilli powder and salt. Cook for 10 minutes over medium heat, until the sauce darkens and the oil starts to separate at the edges.</p></div></li>
        <li><div><h3>Simmer the chicken</h3><p>Return the chicken and any resting juices to the pan with 100 ml water. Cover and simmer gently for 15 minutes, until the chicken is cooked through.</p></div></li>
        <li><div><h3>Finish with cream</h3><p>Lower the heat, stir in the cream and the slit green chilli, and simmer uncovered for 3 minutes. Taste and adjust the salt.</p></div></li>
        <li><div><h3>Rest</h3><p>Take the pan off the heat and rest for 5 minutes before scattering with coriander. Serve with rice or roti.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Cook's notes</h2>
        <ul>
          <li>Browning the chicken first is what gives the sauce its depth. Do not skip it.</li>
          <li>Let the tomato cook until the oil separates. Rushing this leaves the curry tasting flat.</li>
          <li>The curry improves overnight. Cool quickly, refrigerate, and reheat gently with a splash of water.</li>
        </ul>
