  <section class="section section-white page-body">
    <div class="container prose">
      <h2>Why this site exists</h2>
      <p>Most chicken recipes online are written to rank, not to cook. You scroll past a childhood memory, three ad slots and a photo gallery before you find out what temperature the oven should be. Chick Delights is the opposite: the method starts at step one, the quantities are in grams, and the tips sit at the bottom where they belong.</p>
      <p>Every recipe here was cooked in a normal domestic kitchen, on a normal stove, with equipment you probably already own. No sous-vide, no blowtorch, no ingredients that need a specialist import.</p>

      <h2>How we test</h2>
      <p><strong>First cook.</strong> We write an idea, cook it once, and fix the obvious problems: dry chicken, a glaze that splits, a sauce that is too thin.</p>
      <p><strong>Second cook.</strong> We cook it again using only the written method, with no notes from the first attempt. If we have to guess, the method is wrong.</p>
      <p><strong>Third cook.</strong> A different person follows the page from scratch and reports anything unclear. Only then does it get published.</p>
      <p>We also keep a thermometer in the thickest part of every piece. Chicken is done at 75&deg;C, and that number appears in the method of every recipe on the site.</p>

      <h2>What we do not do</h2>
      <ul>
        <li><strong>No invented quantities.</strong> If a number is on the page, it was weighed.</li>
        <li><strong>No paid placements.</strong> No brand pays to appear in a recipe.</li>
        <li><strong>No nutrition claims.</strong> The nutrition tables are estimates, not medical advice.</li>
        <li><strong>No 2,000-word origin story.</strong> The recipe comes first.</li>
      </ul>

      <h2>The kitchen</h2>
      <p>Chick Delights is run by Emma Johnson from a home kitchen in Gaston, South Carolina, with one oven that runs about 5&deg;C hot. That is listed here because it matters: if your oven runs cold, add five minutes and check with a thermometer rather than the clock.</p>

      <h2>Corrections</h2>
      <p>If a recipe does not work, we want to know. Email <a href="mailto:info@chickdelights.site">info@chickdelights.site</a> with the recipe name, what happened, and a photo if you have one. Corrections are logged on the page with the date they were made.</p>
    </div>
  </section>

