  <section class="section section-white page-body">
    <div class="container prose">
      <h2>1. Temperatur schl&auml;gt Zeit</h2>
      <p>In jedem Rezept hier steht &bdquo;bis 75&nbsp;&deg;C in der dicksten Stelle&ldquo;. Diese Zahl z&auml;hlt. Eine d&uuml;nne Keule ist in 12 Minuten gar, eine dicke Brust braucht 22. Ein g&uuml;nstiges Einstichthermometer nimmt das Raten f&uuml;r immer weg.</p>

      <h2>2. Fr&uuml;h salzen, nicht am Ende</h2>
      <p>Salze 30 Minuten vor dem Kochen, bei gr&ouml;&szlig;eren St&uuml;cken am Abend vorher. Salz zieht Feuchtigkeit an die Oberfl&auml;che, l&ouml;st sich und geht als gew&uuml;rzte Lake zur&uuml;ck ins Fleisch. Salzen am Ende w&uuml;rzt nur die Oberfl&auml;che.</p>

      <h2>3. Mit Buttermilch oder Joghurt marinieren</h2>
      <p>Beides ist mild sauer und dickfl&uuml;ssig genug, um zu haften. Acht Stunden in Buttermilch bringen einer H&auml;hnchenkeule mehr als jede Trockenw&uuml;rzung. Joghurt funktioniert genauso f&uuml;r Tandoori-Marinaden.</p>

      <h2>4. Ruhen lassen, bevor du schneidest</h2>
      <p>F&uuml;nf Minuten auf einem Brett, locker abgedeckt. Die S&auml;fte, die sonst auf den Teller laufen, verteilen sich stattdessen im Fleisch. Schneidest du sofort, verlierst du sie.</p>

      <h2>5. Sicher auftauen</h2>
      <p>Im K&uuml;hlschrank, auf der untersten Ablage, in einer Sch&uuml;ssel. Nie auf der Arbeitsfl&auml;che. Ein 1,5-kg-Vogel braucht etwa 24 Stunden. Kleinere St&uuml;cke brauchen 8&ndash;12.</p>

      <h2>6. Mit Plan einfrieren</h2>
      <p>Flach und portioniert einfrieren, mit Datum beschriften und innerhalb von drei Monaten verbrauchen. &Uuml;ber Nacht im K&uuml;hlschrank auftauen &mdash; nie in warmem Wasser.</p>

      <h2>Ger&auml;te, auf die es wirklich ankommt</h2>
