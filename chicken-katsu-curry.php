      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Sauce ansetzen</h3><p>1 EL Öl in einer Pfanne erhitzen und Zwiebel und Karotten 8 Minuten garen, bis sie weich sind und gerade Farbe nehmen.</p></div></li>
        <li><div><h3>Curry aufbauen</h3><p>Currypulver und das zusätzliche Mehl einrühren und 1 Minute garen. Die Brühe nach und nach angießen und dabei rühren, damit keine Klumpen entstehen. Sojasauce und Honig dazugeben und 12 Minuten köcheln lassen.</p></div></li>
        <li><div><h3>Pürieren</h3><p>Die Sauce fein pürieren, zurück in die Pfanne geben und warm halten. Ist sie zu dick, mit etwas Brühe verdünnen.</p></div></li>
        <li><div><h3>Hähnchen panieren</h3><p>Jede Brust aufschneiden, sodass sie gleichmäßig 1,5 cm dick ist, und salzen. Erst in Mehl, dann in Ei, dann in Panko wenden und die Brösel fest andrücken.</p></div></li>
        <li><div><h3>Schnitzel braten</h3><p>Das restliche Öl in einer breiten Pfanne bei mittlerer Hitze erhitzen. Die Schnitzel je Seite 3 bis 4 Minuten braten, bis sie tiefgolden sind und innen 75 °C erreichen. In zwei Portionen braten, damit die Pfanne heiß bleibt.</p></div></li>
        <li><div><h3>Ruhen und schneiden</h3><p>Die Schnitzel 3 Minuten auf einem Gitter ruhen lassen, dann in Streifen schneiden. Durch das Ruhen bleibt die Kruste beim Schneiden dran.</p></div></li>
        <li><div><h3>Servieren</h3><p>Das Curry über den Reis löffeln und die Katsu-Streifen darauflegen. Sofort servieren, mit eingelegtem Ingwer, falls vorhanden.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Das Aufschneiden der Brust entscheidet zwischen trockenem und saftigem Katsu. Auf gleichmäßige Dicke achten.</li>
          <li>Panko, keine normalen Semmelbrösel. Die flockige Struktur macht die Kruste splittrig.</li>
          <li>Die Sauce lässt sich bis zu 2 Monate einfrieren. Doppelte Menge kochen und sich später dafür bedanken.</li>
        </ul>
      </section>

