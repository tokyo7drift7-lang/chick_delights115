      <h2>Zubereitung</h2>
      <ol class="steps">
        <li><div><h3>Hähnchen anbraten</h3><p>1 EL Ghee in einem tiefen Topf bei hoher Hitze erhitzen. Das Hähnchen in zwei Portionen je etwa 3 Minuten anbraten und beiseitestellen. Nicht durchgaren.</p></div></li>
        <li><div><h3>Basis aufbauen</h3><p>Die Hitze reduzieren, restliches Ghee und Kreuzkümmelsamen dazugeben. Wenn sie zischen, die Zwiebel zugeben und 8 Minuten garen, bis sie weich und an den Rändern goldbraun ist.</p></div></li>
        <li><div><h3>Aromaten zugeben</h3><p>Ingwer-Knoblauch-Paste einrühren und 1 Minute garen, bis der rohe Geruch verschwindet. Nicht bräunen lassen.</p></div></li>
        <li><div><h3>Tomate einkochen</h3><p>Passierte Tomaten, Kurkuma, Garam Masala, Chilipulver und Salz dazugeben. 10 Minuten bei mittlerer Hitze garen, bis die Sauce dunkler wird und sich das Öl am Rand absetzt.</p></div></li>
        <li><div><h3>Hähnchen schmoren</h3><p>Das Hähnchen mit den ausgetretenen Säften und 100 ml Wasser zurück in den Topf geben. Abgedeckt 15 Minuten sanft köcheln lassen, bis das Hähnchen durchgegart ist.</p></div></li>
        <li><div><h3>Mit Sahne verfeinern</h3><p>Die Hitze reduzieren, Sahne und die eingeschnittene grüne Chili einrühren und 3 Minuten offen köcheln lassen. Abschmecken und salzen.</p></div></li>
        <li><div><h3>Ruhen</h3><p>Den Topf vom Herd nehmen und 5 Minuten ruhen lassen, dann mit Koriander bestreuen. Mit Reis oder Roti servieren.</p></div></li>
      </ol>

      <section class="tip-box">
        <h2>Tipps aus der Küche</h2>
        <ul>
          <li>Das Anbraten des Hähnchens gibt der Sauce ihre Tiefe. Nicht überspringen.</li>
          <li>Die Tomate einkochen, bis sich das Öl absetzt. Wer hier hetzt, bekommt ein flaches Curry.</li>
          <li>Das Curry wird über Nacht besser. Schnell abkühlen, kalt stellen und mit einem Schluck Wasser sanft aufwärmen.</li>
        </ul>
      </section>

